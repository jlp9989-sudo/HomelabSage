"""`homelabsage eval-routing` — measure which models can drive tool routing.

Runs the golden routing scenarios against every selected candidate model
(a local llama-server + free cloud tiers whose API key is in the env),
scores each on valid-JSON / tool-correct / args / chaining / hallucination /
confirmation-gating / latency, and writes a committed matrix (Markdown + a
JSON sidecar). The model that wins this is the brain of the conversational
interface, so the matrix is meant to be checked in and tracked over time.

This is the LIVE layer: it talks to real endpoints and is never run in CI.
The offline CI suite replays recorded fixtures via `eval.runner.score_records`.

Privacy: no endpoint/key is hardcoded. Local model names come from `--local`
(or `HLS_EVAL_LOCAL_MODELS`); the local endpoint from `--local-endpoint` (or
`HLS_EVAL_LOCAL_ENDPOINT`, default localhost); cloud keys from standard env
vars. Nothing private is written into the committed matrix beyond model
labels and metrics.
"""

from __future__ import annotations

import asyncio
import json
import os
from pathlib import Path

import typer

from ..eval.candidates import build_candidates
from ..eval.runner import ModelRun, run_candidate
from ..eval.scenarios import SCENARIOS
from ._common import VERBOSE_OPT, app, console, setup_logging


def _load_catalog() -> dict[str, dict]:
    from ..mcp_tools import TOOLS
    return TOOLS


def _local_models(opt: str) -> list[str]:
    raw = opt or os.environ.get("HLS_EVAL_LOCAL_MODELS", "")
    return [m.strip() for m in raw.split(",") if m.strip()]


def _matrix_markdown(runs: list[ModelRun], scenario_ids: list[str]) -> str:
    lines = [
        "# Routing model-validity matrix",
        "",
        "Generated by `homelabsage eval-routing`. Each row is one candidate "
        "model scored against the golden routing scenarios "
        "(`homelabsage/eval/scenarios.py`). Higher is better except "
        "**Halluc.** (lower is better).",
        "",
        "| Model | Pass% | JSON% | Tool% | Args% | Chain% | Halluc.% | Confirm% | n | err | p50 ms | p95 ms |",
        "|---|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|",
    ]
    for run in sorted(runs, key=lambda r: r.report.pct_passed, reverse=True):
        r = run.report
        p50 = "—" if r.latency_p50_ms is None else str(r.latency_p50_ms)
        p95 = "—" if r.latency_p95_ms is None else str(r.latency_p95_ms)
        lines.append(
            f"| {r.model} | {r.pct_passed} | {r.pct_valid_json} | "
            f"{r.pct_tool_correct} | {r.pct_args_correct} | "
            f"{r.pct_chaining_correct} | {r.pct_hallucinated} | "
            f"{r.pct_confirmation_correct} | {r.n} | {r.n_errors} | {p50} | {p95} |"
        )
    lines += ["", f"Scenarios ({len(scenario_ids)}): " + ", ".join(scenario_ids), ""]
    return "\n".join(lines)


def _matrix_json(runs: list[ModelRun]) -> dict:
    return {
        "scenarios": [s.id for s in SCENARIOS],
        "models": [run.report.as_dict() for run in runs],
        "records": [
            {
                "model": rec.model,
                "scenario_id": rec.scenario_id,
                "raw": rec.raw,
                "latency_ms": rec.latency_ms,
                "error": rec.error,
            }
            for run in runs
            for rec in run.records
        ],
    }


@app.command(name="eval-routing")
def eval_routing_cmd(
    local: str = typer.Option(
        "", "--local",
        help=(
            "Comma-separated local model names served by your llama-server "
            "(e.g. 'Qwen3.6-35B-Abl,Gemma4-26B-Abl'). Defaults to "
            "$HLS_EVAL_LOCAL_MODELS."
        ),
    ),
    local_endpoint: str = typer.Option(
        "", "--local-endpoint",
        help="Base URL of the local OpenAI-compatible server. Defaults to "
             "$HLS_EVAL_LOCAL_ENDPOINT or http://localhost:11434.",
    ),
    include_cloud: bool = typer.Option(
        True, "--cloud/--no-cloud",
        help="Also test free cloud models whose API key is in the env "
             "(GEMINI_API_KEY / GROQ_API_KEY / OPENROUTER_API_KEY).",
    ),
    out: str = typer.Option(
        "docs/eval/routing-matrix.md", "--out",
        help="Markdown matrix output path.",
    ),
    json_out: str = typer.Option(
        "docs/eval/routing-matrix.json", "--json-out",
        help="JSON sidecar (metrics + raw outputs → reusable as CI fixtures).",
    ),
    only: str = typer.Option(
        "", "--only",
        help="Comma-separated scenario ids to run a subset (default: all).",
    ),
    verbose: bool = VERBOSE_OPT,
) -> None:
    """Benchmark candidate models on agent-routing reliability."""
    setup_logging(verbose)
    catalog = _load_catalog()

    local_models = _local_models(local)
    candidates = build_candidates(
        local_models=local_models,
        local_endpoint=local_endpoint or None,
        include_cloud=include_cloud,
    )
    if not candidates:
        console.print(
            "[red]No candidates.[/red] Pass --local <models> (or set "
            "$HLS_EVAL_LOCAL_MODELS), and/or export a cloud API key with "
            "--cloud."
        )
        raise SystemExit(2)

    scenarios = SCENARIOS
    if only:
        wanted = {s.strip() for s in only.split(",") if s.strip()}
        scenarios = [s for s in SCENARIOS if s.id in wanted]
        if not scenarios:
            console.print(f"[red]No scenarios match {sorted(wanted)}.[/red]")
            raise SystemExit(2)

    console.print(
        f"[cyan]Evaluating {len(candidates)} model(s) on "
        f"{len(scenarios)} scenario(s)…[/cyan]"
    )

    async def _run_all() -> list[ModelRun]:
        runs: list[ModelRun] = []
        for cand in candidates:
            console.print(f"  → [bold]{cand.label}[/bold]")

            def _progress(sc, score, _label=cand.label):
                mark = "[green]✓[/green]" if score.passed else (
                    "[red]ERR[/red]" if score.error else "[yellow]✗[/yellow]"
                )
                console.print(f"      {mark} {sc.id}", highlight=False)

            run = await run_candidate(
                cand, catalog, scenarios, on_scenario=_progress if verbose else None,
            )
            r = run.report
            console.print(
                f"    {cand.label}: pass {r.pct_passed}% | json {r.pct_valid_json}% "
                f"| tool {r.pct_tool_correct}% | halluc {r.pct_hallucinated}% "
                f"| err {r.n_errors}/{r.n}"
            )
            runs.append(run)
        return runs

    runs = asyncio.run(_run_all())

    out_path = Path(out)
    json_path = Path(json_out)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(
        _matrix_markdown(runs, [s.id for s in scenarios]), encoding="utf-8",
    )
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(
        json.dumps(_matrix_json(runs), ensure_ascii=False, indent=2), encoding="utf-8",
    )
    console.print(f"[green]Wrote[/green] {out_path} and {json_path}")
